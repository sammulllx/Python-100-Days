# 参数默认值
# f1 函数有三个参数，b 和 c 有默认值
# a 是必选参数，b 的默认值是 5，c 的默认值是 10


def f1(a, b=5, c=10):
    # 返回 a + (b * 2) + (c * 3)
    return a + b * 2 + c * 3


# 调用 f1 函数，传入三个参数，a=1, b=2, c=3
# 结果为 1 + 2*2 + 3*3 = 1 + 4 + 9 = 14
print(f1(1, 2, 3))

# 调用 f1 函数，传入两个参数，a=100, b=200，c 使用默认值 10
# 结果为 100 + 200*2 + 10*3 = 100 + 400 + 30 = 530
print(f1(100, 200))

# 调用 f1 函数，传入一个参数，a=100，b 和 c 都使用默认值
# 结果为 100 + 5*2 + 10*3 = 100 + 10 + 30 = 140
print(f1(100))

# 使用关键字参数来调用 f1 函数，参数顺序可自由指定
# 结果为 1 + 3*2 + 2*3 = 1 + 6 + 6 = 13
print(f1(c=2, b=3, a=1))


# 可变参数
# f2 函数可以接受任意数量的参数
# *args 用来捕获所有传入的参数并将它们组合成一个元组
def f2(*args):
    sum = 0  # 初始化 sum 变量
    # 遍历所有传入的参数并求和
    for num in args:
        sum += num
    return sum  # 返回总和


# 调用 f2 函数，传入三个参数，返回 1 + 2 + 3 = 6
print(f2(1, 2, 3))

# 调用 f2 函数，传入五个参数，返回 1 + 2 + 3 + 4 + 5 = 15
print(f2(1, 2, 3, 4, 5))

# 调用 f2 函数，不传入任何参数，返回 0
print(f2())


# 关键字参数
# f3 函数可以接受任意数量的关键字参数
# **kw 用来捕获所有传入的关键字参数并将它们组合成一个字典
def f3(**kw):
    # 如果关键字参数中有 'name' 键，输出欢迎信息
    if 'name' in kw:
        print('欢迎你%s!' % kw['name'])
    # 如果关键字参数中有 'tel' 键，输出电话信息
    elif 'tel' in kw:
        print('你的联系电话是: %s!' % kw['tel'])
    # 如果既没有 'name' 也没有 'tel'，输出未找到信息
    else:
        print('没找到你的个人信息!')


# 定义一个包含 'name' 和 'age' 键的字典
param = {'name': '骆昊', 'age': 38}

# 调用 f3 函数，使用字典解包，将 param 传入
# 结果输出 '欢迎你骆昊!'
f3(**param)

# 调用 f3 函数，直接传入关键字参数
# 结果输出 '欢迎你骆昊!'
f3(name='骆昊', age=38, tel='13866778899')

# 调用 f3 函数，传入关键字参数，没有 'name' 键，只有 'tel' 键
# 结果输出 '你的联系电话是: 13866778899!'
f3(user='骆昊', age=38, tel='13866778899')

# 调用 f3 函数，没有 'name' 和 'tel' 键
# 结果输出 '没找到你的个人信息!'
f3(user='骆昊', age=38, mobile='13866778899')
