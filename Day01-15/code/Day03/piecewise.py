"""
分段函数求值
        3x - 5  (x > 1)
f(x) =  x + 2   (-1 <= x <= 1)
        5x + 3  (x < -1)

该程序根据用户输入的 x 值，计算并输出分段函数 f(x) 的值。
Author: 骆昊
Date: 2018-02-28
"""

# 从用户获取输入值 x，并将其转换为浮点数类型
x = float(input('x = '))

# 根据分段函数的条件进行判断并计算相应的 y 值
if x > 1:
    # 如果 x 大于 1，使用公式 y = 3 * x - 5
    y = 3 * x - 5
elif x >= -1:
    # 如果 x 在 -1 到 1 之间（包括 -1 和 1），使用公式 y = x + 2
    y = x + 2
else:
    # 如果 x 小于 -1，使用公式 y = 5 * x + 3
    y = 5 * x + 3

# 输出计算结果，%.2f 表示保留两位小数
print('f(%.2f) = %.2f' % (x, y))
